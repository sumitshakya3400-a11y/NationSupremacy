// build-pages-worker.mjs — emit the Pages advanced-mode worker (`_worker.js`).
//
// Why this exists: the Pages *assets* upload endpoint (/pages/assets/upload)
// requires an `Authorization: Bearer <upload JWT>` header that the connected
// Cloudflare integration cannot set, so a static-asset deployment is impossible
// from this environment. The deployment endpoint does accept `_worker.js` as an
// inline part, which Pages runs as an Advanced Mode function at the project
// root. That keeps the site on Pages (nation-supremacy.pages.dev) without a
// static-asset upload. See Report 12 §4.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const BUILD = '2026-10-23';

const page = await readFile(join(root, 'site', 'index.html'), 'utf8');

if (/Project X/.test(page) || /nationsphere/i.test(page)) {
  throw new Error('the public page must not carry the internal codename or the retired brand');
}
if (!page.includes('<title>Nation Supremacy</title>') || !page.includes('<h1>Nation Supremacy</h1>')) {
  throw new Error('the public page must carry the official name in its title and heading');
}
if (Buffer.byteLength(page, 'utf8') !== page.length) {
  throw new Error('the page must stay ASCII-only for the base64 deploy path');
}

const worker = `// Generated by scripts/build-pages-worker.mjs -- do not edit by hand.
// Nation Supremacy feasibility preview, Pages Advanced Mode (_worker.js).
// Static page, no user data, no gameplay, no credentials.

const PAGE = ${JSON.stringify(page)};
const BUILD = ${JSON.stringify(BUILD)};

const SECURITY_HEADERS = {
  'content-security-policy':
    "default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  'x-content-type-options': 'nosniff',
  'referrer-policy': 'no-referrer',
  'x-frame-options': 'DENY',
  'permissions-policy': 'geolocation=(), microphone=(), camera=()'
};

export default {
  async fetch(request) {
    const url = new URL(request.url);

    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method not allowed\\n', {
        status: 405,
        headers: { allow: 'GET, HEAD', 'content-type': 'text/plain; charset=utf-8', ...SECURITY_HEADERS }
      });
    }

    if (url.pathname === '/' || url.pathname === '/index.html') {
      return new Response(request.method === 'HEAD' ? null : PAGE, {
        headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'public, max-age=60', ...SECURITY_HEADERS }
      });
    }

    if (url.pathname === '/health') {
      return new Response(JSON.stringify({
        service: 'nation-supremacy-site',
        status: 'ok',
        build: BUILD,
        role: 'feasibility preview, not the game',
        hosting: 'cloudflare-pages-advanced-mode'
      }) + '\\n', {
        headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store', ...SECURITY_HEADERS }
      });
    }

    return new Response('Not found\\n', {
      status: 404,
      headers: { 'content-type': 'text/plain; charset=utf-8', ...SECURITY_HEADERS }
    });
  }
};
`;

await mkdir(join(root, 'dist'), { recursive: true });
await writeFile(join(root, 'dist', 'pages-worker.js'), worker, 'utf8');
await writeFile(join(root, 'dist', 'pages-worker.b64'), Buffer.from(worker, 'utf8').toString('base64'), 'utf8');
console.log(`built dist/pages-worker.js (${worker.length} bytes) and dist/pages-worker.b64`);
