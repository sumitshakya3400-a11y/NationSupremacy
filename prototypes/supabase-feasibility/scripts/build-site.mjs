// build-site.mjs — wrap the static page in a Worker module.
//
// The Cloudflare connector used for this spike can upload a Worker script but
// cannot set the Authorization header that the Workers static-assets upload
// requires, so the page is served by the Worker itself. That is a real
// deployment, but it is not the static-asset pipeline; see Report 11 §14.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const BUILD = '2026-10-23';

const page = await readFile(join(root, 'site', 'index.html'), 'utf8');

if (/Project X/.test(page)) {
  throw new Error('the public page must never carry the internal codename');
}
if (!page.includes('<title>Nation Supremacy</title>') || !page.includes('<h1>Nation Supremacy</h1>')) {
  throw new Error('the public page must carry the official name in its title and heading');
}

// The Cloudflare connector uploads scripts as classic (service-worker) modules,
// so the entry point is addEventListener rather than an ES module export.
const worker = `// Generated by scripts/build-site.mjs — do not edit by hand.
// Nation Supremacy feasibility preview. Static page, no user data, no gameplay.

const PAGE = ${JSON.stringify(page)};
const BUILD = ${JSON.stringify(BUILD)};

const SECURITY_HEADERS = {
  'content-security-policy':
    "default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  'x-content-type-options': 'nosniff',
  'referrer-policy': 'no-referrer',
  'x-frame-options': 'DENY'
};

async function handle(request) {
    const url = new URL(request.url);

    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method not allowed\\n', {
        status: 405,
        headers: { allow: 'GET, HEAD', 'content-type': 'text/plain; charset=utf-8' }
      });
    }

    if (url.pathname === '/health') {
      return new Response(JSON.stringify({
        service: 'nation-supremacy-site',
        status: 'ok',
        build: BUILD,
        role: 'feasibility preview, not the game',
        hosting: 'cloudflare-worker'
      }) + '\\n', {
        headers: {
          'content-type': 'application/json; charset=utf-8',
          'cache-control': 'no-store',
          ...SECURITY_HEADERS
        }
      });
    }

    if (url.pathname === '/' || url.pathname === '/index.html') {
      return new Response(request.method === 'HEAD' ? null : PAGE, {
        headers: {
          'content-type': 'text/html; charset=utf-8',
          'cache-control': 'public, max-age=60',
          ...SECURITY_HEADERS
        }
      });
    }

    return new Response('Not found\\n', {
      status: 404,
      headers: { 'content-type': 'text/plain; charset=utf-8', ...SECURITY_HEADERS }
    });
}

addEventListener('fetch', (event) => {
  event.respondWith(handle(event.request));
});
`;

await mkdir(join(root, 'dist'), { recursive: true });
await writeFile(join(root, 'dist', 'worker.js'), worker, 'utf8');
console.log(`built dist/worker.js (${worker.length} bytes, page ${page.length} bytes)`);
